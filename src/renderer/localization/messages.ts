const dictionaries: Record<LanguageCode, Partial<Record<MessageKey, string>>> = {
  'zh-CN': zhCNMessages,
  'en-US': enUSMessages
}

export function normalizeLanguage(value: unknown): LanguageCode {
  return value === 'en-US' ? 'en-US' : DEFAULT_LANGUAGE
}

export function translate(
  language: LanguageCode,
  key: MessageKey,
  params: Record<string, string | number> = {}
): string {
  const template = dictionaries[language][key] ?? zhCNMessages[key]

  return Object.entries(params).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    template
  )
}
